ALL_VARIANT_TYPES = STANDARD_VARIANTS + BALL_VARIANTS + SPECIAL_VARIANTS

_RANK = {variant_type: i for i, variant_type in enumerate(ALL_VARIANT_TYPES)}


def variant_sort_key(variant_type: str) -> int:
    """Unknown types sort after every known one."""
    return _RANK.get(variant_type, len(_RANK))


def variant_order_expr(column):
    """SQL equivalent of variant_sort_key, for ORDER BY."""
    return case(_RANK, value=column, else_=len(_RANK))
